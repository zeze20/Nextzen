export type MessageKey = keyof typeof tr;

const tables: Record<Lang, Record<MessageKey, string>> = { tr, en };

let current: Lang = "tr";
const listeners = new Set<(lang: Lang) => void>();

export function getLanguage(): Lang {
  return current;
}

export function setLanguage(lang: Lang): void {
  current = lang;
  if (typeof document !== "undefined") document.documentElement.lang = lang;
  for (const listener of listeners) listener(lang);
}

export function translate(lang: Lang, key: MessageKey): string {
  return tables[lang][key];
}

export function useI18n(): { lang: Lang; t: (key: MessageKey) => string } {
  const [lang, setLang] = useState<Lang>(current);
  useEffect(() => {
    setLang(current);
    const listener = (next: Lang) => setLang(next);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);
  return { lang, t: (key) => translate(lang, key) };
}
